"use client";

import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { KeyRoundIcon, ShieldCheckIcon, ShieldIcon } from "lucide-react";
import { toast } from "sonner";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Spinner } from "@/components/ui/spinner";
import { confirmTotpEnrollment, removeTotpFactor, startTotpEnrollment, verifyTotp } from "./actions";

function CodeInput({ value, onChange, id }: { value: string; onChange: (v: string) => void; id: string }) {
  return (
    <Input
      id={id}
      value={value}
      onChange={(e) => onChange(e.target.value.replace(/\D/g, "").slice(0, 6))}
      inputMode="numeric"
      autoComplete="one-time-code"
      pattern="\d{6}"
      placeholder="123456"
      aria-label="6-digit code"
      className="tabular text-center text-2xl tracking-[0.4em] md:text-2xl"
      autoFocus
    />
  );
}

/** Settings card: turn TOTP two-factor on or off. */
export function TwoFactorCard({ enrolled, verifiedFactorIds, aal2 }: { enrolled: boolean; verifiedFactorIds: string[]; aal2: boolean }) {
  const [pending, start] = useTransition();
  const [setup, setSetup] = useState<{ factorId: string; qrCode: string; secret: string } | null>(null);
  const [value, setValue] = useState("");

  if (setup) {
    return (
      <div className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm">
          <li>Open an authenticator app (Google Authenticator, Microsoft Authenticator, 1Password…).</li>
          <li>Scan this code, or enter the key below.</li>
          <li>Type the 6-digit code it shows.</li>
        </ol>
        {/* QR code is an SVG data URL generated by Supabase Auth. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={setup.qrCode} alt="QR code for your authenticator app" className="mx-auto size-48 rounded-xl bg-white p-2" />
        <p className="text-center font-mono text-xs break-all text-muted-foreground select-all">{setup.secret}</p>
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            start(async () => {
              const r = await confirmTotpEnrollment(setup.factorId, value);
              if (!r.ok) toast.error(r.error);
              else {
                toast.success(r.message);
                setSetup(null);
                setValue("");
              }
            });
          }}
        >
          <CodeInput id="mfa-enrol-code" value={value} onChange={setValue} />
          <div className="flex gap-2">
            <Button type="submit" className="flex-1" disabled={pending || value.length !== 6}>
              {pending ? <Spinner /> : null} Turn on
            </Button>
            <Button type="button" variant="ghost" onClick={() => setSetup(null)}>
              Cancel
            </Button>
          </div>
        </form>
      </div>
    );
  }

  return (
    <div className="flex items-start gap-3">
      {enrolled ? <ShieldCheckIcon className="mt-0.5 size-5 shrink-0 text-success" aria-hidden /> : <ShieldIcon className="mt-0.5 size-5 shrink-0 text-muted-foreground" aria-hidden />}
      <div className="flex-1 space-y-2 text-sm">
        <p className="font-medium">{enrolled ? "Two-factor authentication is on" : "Two-factor authentication is off"}</p>
        <p className="text-muted-foreground">
          {enrolled
            ? aal2
              ? "This session is verified, so sensitive documents are visible."
              : "Sensitive documents stay hidden until you verify with a code in this session."
            : "Turn it on to store and open sensitive documents such as passports, IDs and medical records."}
        </p>
        <div className="flex flex-wrap gap-2 pt-1">
          {!enrolled ? (
            <Button
              disabled={pending}
              onClick={() =>
                start(async () => {
                  const r = await startTotpEnrollment();
                  if (!r.ok) toast.error(r.error);
                  else setSetup(r.data);
                })
              }
            >
              {pending ? <Spinner /> : <KeyRoundIcon data-icon="inline-start" />} Set up authenticator app
            </Button>
          ) : aal2 ? (
            <Button
              variant="outline"
              disabled={pending}
              onClick={() =>
                start(async () => {
                  for (const id of verifiedFactorIds) {
                    const r = await removeTotpFactor(id);
                    if (!r.ok) {
                      toast.error(r.error);
                      return;
                    }
                  }
                  toast.success("Two-factor authentication removed");
                })
              }
            >
              Turn off
            </Button>
          ) : null}
        </div>
      </div>
    </div>
  );
}

/** Step-up form used on /verify and inline in the vault. */
export function VerifyForm({ next }: { next: string }) {
  const [pending, start] = useTransition();
  const [value, setValue] = useState("");
  const router = useRouter();
  return (
    <form
      className="space-y-3"
      onSubmit={(e) => {
        e.preventDefault();
        start(async () => {
          const r = await verifyTotp(value);
          if (!r.ok) {
            toast.error(r.error);
            setValue("");
            return;
          }
          toast.success("Verified");
          router.push(next);
        });
      }}
    >
      <CodeInput id="mfa-verify-code" value={value} onChange={setValue} />
      <Button type="submit" size="lg" className="w-full" disabled={pending || value.length !== 6}>
        {pending ? <Spinner /> : null} Verify
      </Button>
    </form>
  );
}
